"""Refresh the service worker's per-file content hashes before publishing media."""
import base64
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent
media = {".webp", ".png", ".jpg", ".jpeg", ".avif", ".gif", ".svg", ".woff", ".woff2"}
versions = {}
for path in sorted(root.rglob("*")):
    relative = path.relative_to(root)
    if any(part.startswith(".") for part in relative.parts) or path.suffix.lower() not in media:
        continue
    digest = hashlib.sha256(path.read_bytes()).digest()
    versions[relative.as_posix()] = base64.b64encode(digest).decode("ascii")

(root / "asset-versions.js").write_text(
    "// Generated by build-asset-versions.py\nconst assetVersions = "
    + json.dumps(versions, indent=2, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
